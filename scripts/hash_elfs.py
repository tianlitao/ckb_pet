#!/usr/bin/env python3
"""Extract CKB code hashes from built contract ELFs.

Usage: python3 scripts/hash_elfs.py
Reads  contracts/target/riscv64imac-unknown-none-elf/release/{pet-type,pet-lock}
Writes deployment/code_hashes.json and web/src/generated/code_hashes.ts
"""
import hashlib
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ELF_DIR = os.path.join(ROOT, "contracts", "target", "riscv64imac-unknown-none-elf", "release")
CONTRACTS = ["pet-type", "pet-lock"]


def code_hash(path: str) -> str:
    with open(path, "rb") as f:
        return hashlib.blake2b(
            f.read(), digest_size=32, person=b"ckb-default-hash"
        ).hexdigest()


def main() -> None:
    hashes = {name: "0x" + code_hash(os.path.join(ELF_DIR, name)) for name in CONTRACTS}
    os.makedirs(os.path.join(ROOT, "deployment"), exist_ok=True)
    out_json = os.path.join(ROOT, "deployment", "code_hashes.json")
    with open(out_json, "w") as f:
        json.dump(
            {
                "note": "code_hash = CKB personalized blake2b256(ELF), valid for "
                "Data1-style deployment. "
                "Out points must be filled in after on-chain deployment.",
                **hashes,
            },
            f,
            indent=2,
        )
    gen_dir = os.path.join(ROOT, "web", "src", "generated")
    os.makedirs(gen_dir, exist_ok=True)
    ts = (
        "// AUTO-GENERATED by scripts/hash_elfs.py — do not edit.\n"
        "// Rebuild contracts and re-run the script to refresh.\n"
        f"export const PET_TYPE_CODE_HASH = \"{hashes['pet-type']}\";\n"
        f"export const PET_LOCK_CODE_HASH = \"{hashes['pet-lock']}\";\n"
    )
    with open(os.path.join(gen_dir, "code_hashes.ts"), "w") as f:
        f.write(ts)
    print(json.dumps(hashes, indent=2))


if __name__ == "__main__":
    main()
