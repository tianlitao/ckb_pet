/**
 * Record an already committed deployment without broadcasting.
 *
 * Usage: node scripts/deploy/_record-deploy.mjs <txHash>
 *       node scripts/deploy/_record-deploy.mjs <txHash> --reuse-pet-lock
 */
import { ccc } from "@ckb-ccc/ccc";
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../..", import.meta.url).pathname;
const txHash = process.argv[2];
const reusePetLock = process.argv.includes("--reuse-pet-lock");
if (!txHash) throw new Error("usage: node scripts/deploy/_record-deploy.mjs <txHash> [--reuse-pet-lock]");

const TYPE_ID_CODE_HASH = "0x00000000000000000000000000000000000000000000000000545950455f4944";
const c = new ccc.ClientPublicTestnet({
  url: "https://testnet.ckb.dev/",
  fallbacks: ["https://testnet.ckbapp.dev/"],
});

const previous = JSON.parse(readFileSync(ROOT + "deployment/deployment.json", "utf8"));
const confirmed = await c.getTransaction(txHash);
if (confirmed?.status !== "committed") {
  throw new Error(`deploy tx ${txHash} is ${confirmed?.status}, not committed`);
}

const petTypeOutput = confirmed.transaction.outputs[0];
if (!petTypeOutput?.type || petTypeOutput.type.codeHash !== TYPE_ID_CODE_HASH) {
  throw new Error("output #0 is not a TYPE_ID script cell");
}
const petTypeScript = ccc.Script.from({
  codeHash: TYPE_ID_CODE_HASH,
  hashType: "type",
  args: petTypeOutput.type.args,
});
const petTypeCodeHash = ccc.hashCkb(petTypeScript.toHex());
const petTypeDataLen = (confirmed.transaction.outputsData[0].length - 2) / 2;

let petLock = previous.petLock;
if (!reusePetLock) {
  const petLockOutput = confirmed.transaction.outputs[1];
  if (!petLockOutput?.type || petLockOutput.type.codeHash !== TYPE_ID_CODE_HASH) {
    throw new Error("output #1 is not a TYPE_ID pet-lock script cell");
  }
  const petLockScript = ccc.Script.from({
    codeHash: TYPE_ID_CODE_HASH,
    hashType: "type",
    args: petLockOutput.type.args,
  });
  petLock = {
    codeHash: ccc.hashCkb(petLockScript.toHex()),
    hashType: "type",
    txHash,
    index: 1,
    dataBytes: (confirmed.transaction.outputsData[1].length - 2) / 2,
  };
}

const info = {
  network: "ckb_testnet",
  deployedAt: new Date().toISOString(),
  deployTx: txHash,
  petTypeArgs: "RFC-0032 TYPE_ID args",
  petType: {
    codeHash: petTypeCodeHash,
    hashType: "type",
    txHash,
    index: 0,
    dataBytes: petTypeDataLen,
  },
  petLock,
  note: "script cells are vault-locked (key burned); references use hash_type type",
};
writeFileSync(ROOT + "deployment/deployment.json", JSON.stringify(info, null, 2));
const ts = `// AUTO-GENERATED by scripts/deploy/2-deploy.mjs — do not edit.
export const DEPLOYMENT = ${JSON.stringify(info, null, 2)} as const;
`;
writeFileSync(ROOT + "web/src/generated/deployment.ts", ts);
console.log(JSON.stringify(info, null, 2));
