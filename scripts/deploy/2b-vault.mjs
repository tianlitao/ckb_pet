/**
 * Step 2b: re-lock the deployed script cells under a burn vault key.
 * The first deploy used the deployer's own lock, so the script cells (69.5k
 * CKB of capacity) look like spendable balance to the deploy wallet — a
 * collector picked them as adopt-tx fuel and the node rejected the tx.
 * Production posture: script cells are locked by a key nobody holds.
 * Data stays byte-identical → same code hashes → only out points change.
 *   node scripts/deploy/2b-vault.mjs
 */
import { ccc } from "@ckb-ccc/ccc";
import { readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";

const ROOT = new URL("../..", import.meta.url).pathname;

const client = () =>
  new ccc.ClientPublicTestnet({
    url: "https://testnet.ckb.dev/",
    fallbacks: ["https://testnet.ckbapp.dev/"],
  });

async function main() {
  if (process.env.ALLOW_LEGACY_VAULT !== "1") {
    throw new Error(
      "legacy Data1 vault migration disabled; current deployment uses TYPE_ID. " +
        "Set ALLOW_LEGACY_VAULT=1 only when deliberately migrating an old deployment.",
    );
  }
  const info = JSON.parse(readFileSync(ROOT + "deployment/deployment.json", "utf8"));
  const { privateKey } = JSON.parse(readFileSync(ROOT + "deployment/deploy-key.json", "utf8"));
  const c = client();
  const signer = new ccc.SignerCkbPrivateKey(c, privateKey);

  // vault lock from a key we throw away — script cells become unspendable
  const vaultPriv = "0x" + randomBytes(32).toString("hex");
  const vaultSigner = new ccc.SignerCkbPrivateKey(c, vaultPriv);
  const vaultLock = (await vaultSigner.getAddressObjs())[0].script;
  void vaultSigner.disconnect();

  const petTypeCell = await c.getCellLive(
    ccc.OutPoint.from({ txHash: info.petType.txHash, index: info.petType.index }),
  );
  const petLockCell = await c.getCellLive(
    ccc.OutPoint.from({ txHash: info.petLock.txHash, index: info.petLock.index }),
  );
  if (!petTypeCell || !petLockCell) throw new Error("script cells not live");

  const tx = ccc.Transaction.default();
  tx.inputs = [
    ccc.CellInput.from({ previousOutput: { txHash: info.petType.txHash, index: info.petType.index } }),
    ccc.CellInput.from({ previousOutput: { txHash: info.petLock.txHash, index: info.petLock.index } }),
  ];
  tx.outputs = [
    ccc.CellOutput.from({ lock: vaultLock, capacity: petTypeCell.cellOutput.capacity }),
    ccc.CellOutput.from({ lock: vaultLock, capacity: petLockCell.cellOutput.capacity }),
  ];
  tx.outputsData = [petTypeCell.outputData, petLockCell.outputData];
  await tx.completeInputsByCapacity(signer);
  await tx.completeFeeBy(signer);
  const txHash = await signer.sendTransaction(tx);
  console.log("vault migration tx:", txHash);
  const confirmed = await c.waitTransaction(txHash, 1, 180_000, 3_000);
  if (!confirmed) throw new Error("not confirmed in time");

  info.petType.txHash = txHash;
  info.petType.index = 0;
  info.petLock.txHash = txHash;
  info.petLock.index = 1;
  info.vaultedAt = new Date().toISOString();
  writeFileSync(ROOT + "deployment/deployment.json", JSON.stringify(info, null, 2));
  const ts = `// AUTO-GENERATED by scripts/deploy/2b-vault.mjs — do not edit.
export const DEPLOYMENT = ${JSON.stringify(info, null, 2)} as const;
`;
  writeFileSync(ROOT + "web/src/generated/deployment.ts", ts);
  console.log("deployment.json + generated/deployment.ts updated");
}

await main();
